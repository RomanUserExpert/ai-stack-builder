def sprite(names):
    out = []
    for n in sorted(names):
        svg = (LUCIDE / f"{n}.svg").read_text(encoding="utf-8")
        inner = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1).strip()
