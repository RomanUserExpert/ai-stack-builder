def icon_for(before, after):
    """Choose a Lucide icon for a wireframe `.icon` placeholder from the markup around it."""
    b = before[-260:]
    text = re.sub(r"<[^>]+>", "", after)[:40].strip()
    if re.search(r'class="product"[^>]*>\s*$', b) or b.rstrip().endswith('<span class="product">'):
        return None  # the product's mark: drawn as the lime square
    if re.search(r'class="(?:[\w-]+ )*search[^"]*"[^>]*>\s*$', b):
        return "search"
    if re.search(r'class="(?:[\w-]+ )*(?:close|remove)[^"]*"[^>]*>\s*$', b) or 'aria-label="Close"' in b[-120:]:
        return "x"
    if re.search(r'class="back"[^>]*>\s*$', b):
        return "arrow-left"
    for label, name in LABEL_ICONS:
        if text.startswith(label):
            return name
    return "circle-dashed"


