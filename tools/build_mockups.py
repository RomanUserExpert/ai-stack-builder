def patch_viewer(pages, flows):
    v = VIEWER.read_text(encoding="utf-8")
    data = json.dumps({"pages": pages, "flows": flows})
    block = (f"<!-- mockups:start -->{MODE_CSS}\n  <script>\n    /* The Wireframe / Design switch (tools/build_mockups.py). Which screens and flows have a mockup. */\n"
             f"    window.WF_MOCKUPS = {data};\n"
             "    /* ?mode=design or ?mode=wire in the address opens the viewer in that mode, and remembers it */\n"
             "    (function () { var q = new URLSearchParams(location.search).get('mode'); if (q === 'design' || q === 'wire') { window.WF_MODE_URL = q; try { localStorage.setItem('wf-mode', q); } catch (e) {} } })();\n"
             "    window.wfMode = function () { try { return localStorage.getItem('wf-mode') || window.WF_MODE_URL || 'wire'; } catch (e) { return window.WF_MODE_URL || 'wire'; } };\n"
             "    window.wfDesign = function (src) {\n"
             "      if (window.wfMode() !== 'design') return src;\n"
             "      var m = src.match(/^\\.\\.\\/prototypes\\/([^\\/]+)\\/(.+)$/);\n"
             "      if (m) return window.WF_MOCKUPS.flows.indexOf(m[1]) >= 0 ? '../mockups/flows/' + m[1] + '/' + m[2] : src;\n"
             "      var p = src.replace(/\\.html$/, '');\n"
             "      return window.WF_MOCKUPS.pages.indexOf(p) >= 0 ? '../mockups/' + src : src;\n"
             "    };\n  </script>\n  <!-- mockups:end -->")
    if "<!-- mockups:start -->" in v:
        v = re.sub(r"<!-- mockups:start -->.*?<!-- mockups:end -->", lambda m: block, v, flags=re.S)
    else:
        v = v.replace("</head>", "  " + block + "\n</head>", 1)
    # renamed: Wireframes and mockups
    v = v.replace("<title>Phase 04 · Wireframes</title>", "<title>Phase 04 · Wireframes and mockups</title>")
    v = v.replace('<span class="wf-name">Wireframes</span></summary>', '<span class="wf-name">Wireframes and mockups</span></summary>')
    v = v.replace('(flow ? "Flows" : "Wireframes")', '(flow ? "Flows" : "Wireframes and mockups")')
    # the switch, beside Show hotspots
    if 'id="wf-mode"' not in v:
        v = v.replace('<button type="button" class="wf-open" id="wf-hotspots"',
                      '<div class="wf-mode" id="wf-mode" role="group" aria-label="View"><button type="button" data-mode="wire">Wireframe</button><button type="button" data-mode="design">Design</button></div>\n        <button type="button" class="wf-open" id="wf-hotspots"', 1)
    # the loads go through wfDesign()
    v = v.replace('open.href = page + ".html";', 'open.href = wfDesign(page + ".html");')
    v = v.replace('else load(page + ".html");', 'else load(wfDesign(page + ".html"));')
    v = v.replace('open.href = "../prototypes/" + flow[0] + "/" + step + ".html";', 'open.href = wfDesign("../prototypes/" + flow[0] + "/" + step + ".html");')
    v = v.replace(r'var m = path.match(/\/prototypes\/([^\/]+)\/([^\/]+?)(?:\.html)?$/);', r'var m = path.match(/\/(?:prototypes|mockups\/flows)\/([^\/]+)\/([^\/]+?)(?:\.html)?$/);')
    # the switch's behaviour: pressed state, and whether this screen or flow has a design yet
    if "/* wf-mode:behaviour */" not in v:
        v = v.replace('    window.addEventListener("hashchange", show);',
                      '''    /* wf-mode:behaviour */
    var modeBox = document.getElementById("wf-mode");
    function syncMode() {
      var mode = wfMode(), page = (location.hash || "#projects-default").slice(1), flow = page.indexOf("flow/") === 0 ? page.slice(5).split("/")[0] : null;
      var has = flow ? WF_MOCKUPS.flows.indexOf(flow) >= 0 : WF_MOCKUPS.pages.indexOf(page) >= 0;
      modeBox.querySelectorAll("button").forEach(function (b) {
        b.setAttribute("aria-pressed", String(b.getAttribute("data-mode") === mode));
        if (b.getAttribute("data-mode") === "design") { if (has) { b.removeAttribute("data-none"); b.title = "Show this in the working style"; } else { b.setAttribute("data-none", ""); b.title = "No mockup of this yet — the wireframe is shown"; } }
      });
    }
    modeBox.addEventListener("click", function (e) {
      var b = e.target.closest("button[data-mode]"); if (!b) return;
      try { localStorage.setItem("wf-mode", b.getAttribute("data-mode")); } catch (err) {}
      syncMode(); show();
    });
    window.addEventListener("hashchange", syncMode);
    syncMode();
    window.addEventListener("hashchange", show);''', 1)
    VIEWER.write_text(v, encoding="utf-8")


def shell(html, flow=False):
    """The frame comes from the kit's shell (07-ui-assembly/ui/shell.html), not from the page: the app header and the
    shared header are replaced by the shell's own markup, keeping the page's current place. The Run bar carries the
    page's own words (where it was entered, what is exported), so it stays — and must have the shell's structure."""
    import build_kit
    sh = build_kit.shell_source()
    shape = lambda h: re.findall(r'class="([^"]*)"', h)
    if flow:  # phase 07 review, F1–F3: the prototype's header carries the case's links; it is checked, not replaced
        for kind, key in (("app-header", "app"), ("run-bar", "run")):
            m = re.search(rf'<header class="{kind}">.*?</header>', html, re.S)
            if m and shape(m.group(0)) != shape(sh[key]):
                raise SystemExit(f"a flow step's {kind} is not the shell's shape")
        return html
    m = re.search(r'<header class="app-header">.*?</header>', html, re.S)
    if m:
        cur = re.search(r'<a href="([^"]+)" aria-current="page">', m.group(0))
        new = sh["app"].replace(' aria-current="page"', "")
        if cur:
            new = new.replace(f'<a href="{cur.group(1)}">', f'<a href="{cur.group(1)}" aria-current="page">', 1)
        return html[:m.start()] + new + html[m.end():]
    m = re.search(r'<header class="shared-header">.*?</header>', html, re.S)
    if m:
        new = sh["receiver"] if 'class="owner"' in m.group(0) else sh["door"]
        return html[:m.start()] + new + html[m.end():]
    m = re.search(r'<header class="run-bar">.*?</header>', html, re.S)
    if m:
        if shape(m.group(0)) != shape(sh["run"]):
            raise SystemExit("a Run bar that is not the shell's shape")
    return html


